
use std::collections::{BTreeMap, HashMap, VecDeque}; // Import sorted price levels, order lookup, and FIFO queues.

#[derive(Debug, Clone, Copy, PartialEq, Eq)] // Enable debugging, copying, and equality checks for order sides.
pub enum Side { // Define the two possible order directions.
    Buy, // A buy order wants to purchase.
    Sell, // A sell order wants to sell.
} // Finish the side definition.

#[derive(Debug, Clone, Copy)] // Allow orders to be copied and printed for debugging.
pub struct Order { // Represent one incoming or resting order.
    pub id: u64, // Store a unique order ID.
    pub side: Side, // Store whether the order buys or sells.
    pub price: u64, // Store price in integer ticks.
    pub quantity: u64, // Store the number of units.
} // Finish the order definition.

#[derive(Debug)] // Allow completed trades to be printed for debugging.
pub struct Trade { // Represent one executed trade.
    pub maker_order_id: u64, // Identify the resting order.
    pub taker_order_id: u64, // Identify the incoming order.
    pub price: u64, // Store the execution price.
    pub quantity: u64, // Store the executed quantity.
} // Finish the trade definition.

pub struct OrderBook { // Hold all resting orders and their lookup index.
    bids: BTreeMap<u64, VecDeque<Order>>, // Group buy orders by price, with prices sorted.
    asks: BTreeMap<u64, VecDeque<Order>>, // Group sell orders by price, with prices sorted.
    order_prices: HashMap<u64, (Side, u64)>, // Map each resting order ID to its side and price.
} // Finish the order-book definition.

impl OrderBook { // Define the order-book operations.
    pub fn new() -> Self { // Create an empty order book.
        Self { // Return the initial book state.
            bids: BTreeMap::new(), // Start with no buy price levels.
            asks: BTreeMap::new(), // Start with no sell price levels.
            order_prices: HashMap::new(), // Start with no indexed orders.
        } // Finish initialization.
    } // Finish the constructor.

    pub fn add_order(&mut self, mut incoming: Order) -> Vec<Trade> { // Match an incoming order and return its trades.
        let mut trades = Vec::new(); // Collect trades generated by this order.

        match incoming.side { // Choose the matching path based on the incoming side.
            Side::Buy => { // A buyer matches against the cheapest sellers.
                while incoming.quantity > 0 { // Continue while the buyer has quantity remaining.
                    let best_ask = match self.asks.keys().next().copied() { // Find the lowest ask price.
                        Some(price) => price, // Use the best available ask.
                        None => break, // Stop if there are no sellers.
                    }; // Finish finding the best ask.

                    if incoming.price < best_ask { break; } // Stop if the buyer's price is too low.

                    let (maker_id, traded_quantity, filled_id, level_empty) = { // Keep the queue borrow inside this block.
                        let queue = self.asks.get_mut(&best_ask).unwrap(); // Get sellers at the best ask.
                        let maker = queue.front_mut().unwrap(); // Select the oldest seller at this price.
                        let maker_id = maker.id; // Save the seller ID before possible removal.
                        let traded_quantity = incoming.quantity.min(maker.quantity); // Trade the smaller available quantity.
                        maker.quantity -= traded_quantity; // Reduce the seller's remaining quantity.
                        incoming.quantity -= traded_quantity; // Reduce the buyer's remaining quantity.
                        let filled_id = if maker.quantity == 0 { Some(maker.id) } else { None }; // Identify a fully filled seller.
                        if filled_id.is_some() { queue.pop_front(); } // Remove the seller if fully filled.
                        (maker_id, traded_quantity, filled_id, queue.is_empty()) // Return trade and cleanup details.
                    }; // Release the queue borrow.

                    trades.push(Trade { maker_order_id: maker_id, taker_order_id: incoming.id, price: best_ask, quantity: traded_quantity }); // Record the trade at the resting ask price.
                    if let Some(id) = filled_id { self.order_prices.remove(&id); } // Remove a filled seller from the lookup index.
                    if level_empty { self.asks.remove(&best_ask); } // Remove the price level if its queue is empty.
                } // Finish matching the buyer.

                if incoming.quantity > 0 { // Keep any unfilled buy quantity.
                    self.order_prices.insert(incoming.id, (Side::Buy, incoming.price)); // Index the resting buy order.
                    self.bids.entry(incoming.price).or_default().push_back(incoming); // Add the buyer to the bid book.
                } // Finish resting the buyer.
            } // Finish buy-side handling.

            Side::Sell => { // A seller matches against the highest-priced buyers.
                while incoming.quantity > 0 { // Continue while the seller has quantity remaining.
                    let best_bid = match self.bids.keys().next_back().copied() { // Find the highest bid price.
                        Some(price) => price, // Use the best available bid.
                        None => break, // Stop if there are no buyers.
                    }; // Finish finding the best bid.

                    if incoming.price > best_bid { break; } // Stop if the buyer's price is too low.

                    let (maker_id, traded_quantity, filled_id, level_empty) = { // Keep the queue borrow inside this block.
                        let queue = self.bids.get_mut(&best_bid).unwrap(); // Get buyers at the best bid.
                        let maker = queue.front_mut().unwrap(); // Select the oldest buyer at this price.
                        let maker_id = maker.id; // Save the buyer ID before possible removal.
                        let traded_quantity = incoming.quantity.min(maker.quantity); // Trade the smaller available quantity.
                        maker.quantity -= traded_quantity; // Reduce the buyer's remaining quantity.
                        incoming.quantity -= traded_quantity; // Reduce the seller's remaining quantity.
                        let filled_id = if maker.quantity == 0 { Some(maker.id) } else { None }; // Identify a fully filled buyer.
                        if filled_id.is_some() { queue.pop_front(); } // Remove the buyer if fully filled.
                        (maker_id, traded_quantity, filled_id, queue.is_empty()) // Return trade and cleanup details.
                    }; // Release the queue borrow.

                    trades.push(Trade { maker_order_id: maker_id, taker_order_id: incoming.id, price: best_bid, quantity: traded_quantity }); // Record the trade at the resting bid price.
                    if let Some(id) = filled_id { self.order_prices.remove(&id); } // Remove a filled buyer from the lookup index.
                    if level_empty { self.bids.remove(&best_bid); } // Remove the price level if its queue is empty.
                } // Finish matching the seller.

                if incoming.quantity > 0 { // Keep any unfilled sell quantity.
                    self.order_prices.insert(incoming.id, (Side::Sell, incoming.price)); // Index the resting sell order.
                    self.asks.entry(incoming.price).or_default().push_back(incoming); // Add the seller to the ask book.
                } // Finish resting the seller.
            } // Finish sell-side handling.
        } // Finish matching based on the order side.

        trades // Return all executed trades.
    } // Finish adding an order.

    pub fn cancel_order(&mut self, order_id: u64) -> bool { // Cancel a resting order by ID.
        let (side, price) = match self.order_prices.get(&order_id).copied() { // Find its recorded location.
            Some(location) => location, // Use the recorded side and price.
            None => return false, // Return false if the order is not indexed.
        }; // Finish looking up the order.

        let book = match side { // Select the correct side of the book.
            Side::Buy => &mut self.bids, // Search the bid book for a buy.
            Side::Sell => &mut self.asks, // Search the ask book for a sell.
        }; // Finish selecting the book.

        let mut removed = false; // Track whether the order was found and removed.
        let mut level_empty = false; // Track whether its price level became empty.

        if let Some(queue) = book.get_mut(&price) { // Find the queue at the recorded price.
            if let Some(index) = queue.iter().position(|order| order.id == order_id) { // Find the order inside the queue.
                queue.remove(index); // Remove the matching order.
                removed = true; // Record successful removal.
                level_empty = queue.is_empty(); // Check whether the queue is now empty.
            } // Finish searching the queue.
        } // Finish accessing the price level.

        if removed { // Update the index only after successful removal.
            self.order_prices.remove(&order_id); // Remove the order's index entry.
            if level_empty { book.remove(&price); } // Remove an empty price level.
        } // Finish cancellation cleanup.

        removed // Report whether cancellation succeeded.
    } // Finish cancellation.

    pub fn best_bid(&self) -> Option<u64> { // Return the highest resting buy price.
        self.bids.keys().next_back().copied() // Read the largest bid price.
    } // Finish best-bid lookup.

    pub fn best_ask(&self) -> Option<u64> { // Return the lowest resting sell price.
        self.asks.keys().next().copied() // Read the smallest ask price.
    } // Finish best-ask lookup.
} // Finish the order-book implementation.
